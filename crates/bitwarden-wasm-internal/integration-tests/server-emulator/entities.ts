import type {
  Cipher,
  EncString,
  Folder,
  Kdf,
  KeyId,
  UnsignedSharedKey,
  V2UpgradeToken,
  WrappedAccountCryptographicState,
} from "@bitwarden/sdk-internal";

import type { EmergencyAccessStatusValue, EmergencyAccessTypeValue } from "./dto";

/** Master-password unlock data as the server holds it. */
export interface StoredMasterPasswordUnlock {
  masterKeyWrappedUserKey: EncString;
  salt: string;
  /** The SDK's `Kdf`; the serializers convert it to the server's numeric form on the way out. */
  kdf: Kdf;
  containedKeyId?: string;
}

/** An account's id, so it cannot be swapped for another id. */
export type AccountId = string & { readonly __brand: "AccountId" };

/** An account as the server holds it. */
export interface UserEntity {
  userId: AccountId;
  email: string;
  accountCryptographicState: WrappedAccountCryptographicState;
  publicKey: string;
  verifyingKey: string | null;
  /** Absent for a V1 account, which has no security state. */
  securityVersion?: number;
  /**
   * The account's KDF settings, held separately from {@link masterPasswordUnlock} because an account
   * with none — key connector, trusted device — still has them and still needs them to initialize.
   */
  kdf: Kdf;
  /**
   * The id of the account's user key.
   *
   * Optional: an account created before key ids existed has none until it backfills one, which is
   * the state `user_key_id_needs_backfill` reports on.
   */
  userKeyId?: KeyId;
  /** `null` for an account with no master password. */
  masterPasswordUnlock: StoredMasterPasswordUnlock | null;
  /**
   * The master password authentication hash the identity service expects, or `null` for an account
   * with no master password.
   */
  masterPasswordAuthenticationHash: string | null;
  /** Set while a V1 to V2 upgrade is outstanding; served in the account's decryption options. */
  upgradeToken?: V2UpgradeToken;
  /** Organization keys sealed to this account, keyed by organization id. */
  organizationKeys: Record<string, string>;
  /** Whether the account has verified its email address. Absent means verified. */
  emailVerified?: boolean;
}

/**
 * A cipher as the server holds it: the encrypted model plus who owns it.
 *
 * Exactly one owner is set. A user cipher lives in one account's vault; an organization cipher is
 * reachable by every member, so it cannot be attributed to the account that happened to create it.
 */
export interface CipherEntity {
  /** The account that owns it, or `null` for an organization cipher. */
  userId: string | null;
  /** The organization that owns it, or `null` for a user cipher. */
  organizationId: string | null;
  cipher: Cipher;
}

/** A folder as the server holds it. Folders are always personal — organizations have collections. */
export interface FolderEntity {
  userId: string;
  folder: Folder;
}

/** A member's role, which decides what it may administer. */
export type OrganizationRole = "owner" | "admin" | "user";

/**
 * How far a member has joined. An accepted member belongs to the organization but holds no
 * organization key until it is confirmed, so it cannot reach organization data yet.
 */
export type OrganizationMemberStatus = "accepted" | "confirmed";

/** A member of an organization, as the server holds it. */
export interface OrganizationMember {
  userId: string;
  role: OrganizationRole;
  status: OrganizationMemberStatus;
  /** The organization key sealed to this member's public key, `null` until confirmed. */
  organizationKeySealedToMember: string | null;
  /** Present only for a member enrolled in account recovery. */
  accountRecoveryKey?: string;
  /**
   * The name of the member's default collection, encrypted with the organization key. Present only
   * for a member that confirmed itself through an invite link, which names the collection.
   */
  defaultCollectionName?: string;
}

/** An organization as the server holds it. */
export interface OrganizationEntity {
  organizationId: string;
  name: string;
  publicKey?: string;
  wrappedPrivateKey?: string;
  organizationKeyId: string | null;
  members: OrganizationMember[];
  /** A disabled organization answers as though it did not exist. */
  enabled: boolean;
  /** Whether the organization's plan includes invite links. */
  useInviteLinks: boolean;
  /** How many members the plan allows, `null` for no limit. */
  seats: number | null;
}

/**
 * An organization's invite link, as the server holds it. An organization has at most one, so the
 * table keys on the organization id.
 */
export interface OrganizationInviteLinkEntity {
  id: string;
  /** Generated by the server; invitees present it alongside the secret only the link carries. */
  code: string;
  organizationId: string;
  allowedDomains: string[];
  /** The sealed invite, opaque to the server. */
  invite: string;
  supportsConfirmation: boolean;
  creationDate: string;
  revisionDate: string;
}

/** An emergency access grant, as the server holds it. */
export interface EmergencyAccessEntity {
  id: string;
  grantorId: AccountId;
  /** `null` until the invited account accepts. */
  granteeId: AccountId | null;
  /** The address the grantor invited. */
  email: string;
  type: EmergencyAccessTypeValue;
  status: EmergencyAccessStatusValue;
  waitTimeDays: number;
  /** The grantor's user key sealed to the grantee, `null` until the grantor confirms. */
  keyEncrypted: UnsignedSharedKey | null;
  /** The token the invite email carries, which the grantee accepts with. */
  inviteToken: string;
}
